const photoTmp = await mkdtemp(path.join(tmpdir(), 'oneshot-player-assets-'));
try {
  const transparent = await sharp({ create: { width: 40, height: 60, channels: 4, background: { r: 20, g: 70, b: 50, alpha: 0 } } }).png().toBuffer();
  const opaque = await sharp({ create: { width: 60, height: 40, channels: 3, background: { r: 150, g: 80, b: 50 } } }).png().toBuffer();
  await Promise.all([writeFile(path.join(photoTmp, 'transparent.png'), transparent), writeFile(path.join(photoTmp, 'opaque.png'), opaque)]);
  const transparentStats = await sharp(path.join(photoTmp, 'transparent.png')).stats();
  const opaqueStats = await sharp(path.join(photoTmp, 'opaque.png')).stats();
  assert.equal(transparentStats.channels[3].min, 0, 'transparent PNG alpha is preserved');
  assert.equal(opaqueStats.channels.length, 3, 'opaque PNG remains opaque');
} finally { await rm(photoTmp, { recursive: true, force: true }); }
